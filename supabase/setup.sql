create table if not exists public.users (
  id integer generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users (id) on delete cascade,
  name text,
  email varchar(320),
  location varchar(255),
  avatar_path text,
  role varchar(16) not null default 'user'
    check (role in ('user', 'client', 'fundi', 'admin')),
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create unique index if not exists users_email_lower_unique
  on public.users (lower(email))
  where email is not null;

create table if not exists public.worker_profiles (
  id integer generated by default as identity primary key,
  "userId" integer not null unique references public.users (id) on delete cascade,
  phone varchar(32),
  experience text,
  "serviceArea" varchar(255) not null,
  availability integer not null default 1 check (availability in (0, 1)),
  "latitudeE6" integer,
  "longitudeE6" integer,
  summary text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public.worker_skills (
  id integer generated by default as identity primary key,
  "workerId" integer not null references public.worker_profiles (id) on delete cascade,
  trade varchar(64) not null,
  constraint worker_skills_worker_trade_unique unique ("workerId", trade)
);

create table if not exists public.jobs (
  id varchar(32) primary key,
  "clientId" integer not null references public.users (id),
  title varchar(160) not null,
  trade varchar(64) not null,
  description text not null,
  "locationText" varchar(255) not null,
  "latitudeE6" integer,
  "longitudeE6" integer,
  "radiusKm" integer not null default 10 check ("radiusKm" > 0),
  "budgetAmount" integer not null check ("budgetAmount" > 0),
  "startDate" varchar(32) not null,
  "contactPreference" varchar(32) not null default 'Call me',
  status varchar(32) not null default 'Posted',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public.job_responses (
  id integer generated by default as identity primary key,
  "jobId" varchar(32) not null references public.jobs (id) on delete cascade,
  "workerId" integer not null references public.worker_profiles (id) on delete cascade,
  status varchar(24) not null default 'Interested',
  "createdAt" timestamptz not null default now(),
  constraint job_responses_job_worker_unique unique ("jobId", "workerId")
);

create table if not exists public.ratings (
  id integer generated by default as identity primary key,
  "jobId" varchar(32) not null references public.jobs (id),
  "clientId" integer not null references public.users (id),
  "workerId" integer not null references public.worker_profiles (id),
  score integer not null check (score between 1 and 5),
  comment text,
  "createdAt" timestamptz not null default now(),
  constraint ratings_job_client_unique unique ("jobId", "clientId")
);

create table if not exists public.reports (
  id varchar(32) primary key,
  "reporterId" integer not null references public.users (id),
  "reportedUserId" integer references public.users (id),
  "reportedJobId" varchar(32) references public.jobs (id),
  "subjectType" varchar(32) not null,
  reason text not null,
  status varchar(24) not null default 'Review',
  "createdAt" timestamptz not null default now(),
  "resolvedAt" timestamptz,
  "resolvedBy" integer references public.users (id)
);

create table if not exists public.conversations (
  id integer generated by default as identity primary key,
  "jobId" varchar(32) not null references public.jobs (id) on delete cascade,
  "clientId" integer not null references public.users (id),
  "workerId" integer not null references public.worker_profiles (id) on delete cascade,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  constraint conversations_job_worker_unique unique ("jobId", "workerId")
);

create table if not exists public.messages (
  id integer generated by default as identity primary key,
  "conversationId" integer not null references public.conversations (id) on delete cascade,
  "senderId" integer not null references public.users (id),
  body varchar(2000) not null,
  "createdAt" timestamptz not null default now(),
  "readAt" timestamptz
);

create table if not exists public.notifications (
  id integer generated by default as identity primary key,
  "userId" integer not null references public.users (id) on delete cascade,
  type varchar(32) not null,
  title varchar(160) not null,
  body varchar(500) not null,
  "jobId" varchar(32) references public.jobs (id) on delete cascade,
  "conversationId" integer references public.conversations (id) on delete cascade,
  "readAt" timestamptz,
  "createdAt" timestamptz not null default now()
);

create index if not exists jobs_client_created_idx
  on public.jobs ("clientId", "createdAt" desc);
create index if not exists jobs_status_trade_idx
  on public.jobs (status, trade);
create index if not exists worker_profiles_availability_idx
  on public.worker_profiles (availability);
create index if not exists worker_skills_trade_idx
  on public.worker_skills (trade);
create index if not exists job_responses_job_idx
  on public.job_responses ("jobId");
create index if not exists ratings_worker_idx
  on public.ratings ("workerId");
create index if not exists reports_status_created_idx
  on public.reports (status, "createdAt" desc);
create index if not exists conversations_client_updated_idx
  on public.conversations ("clientId", "updatedAt" desc);
create index if not exists conversations_worker_updated_idx
  on public.conversations ("workerId", "updatedAt" desc);
create index if not exists messages_conversation_created_idx
  on public.messages ("conversationId", "createdAt");
create index if not exists notifications_user_created_idx
  on public.notifications ("userId", "createdAt" desc);

create or replace function public.sync_mjengolink_auth_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  insert into public.users (auth_user_id, email, name, location, role)
  values (
    new.id,
    new.email,
    nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
    nullif(trim(new.raw_user_meta_data ->> 'location'), ''),
    case
      when new.raw_user_meta_data ->> 'role' in ('client', 'fundi', 'admin') then new.raw_user_meta_data ->> 'role'
      else 'user'
    end
  )
  on conflict (auth_user_id) do update
    set email = excluded.email,
        name = coalesce(excluded.name, public.users.name),
        location = coalesce(nullif(trim(new.raw_user_meta_data ->> 'location'), ''), public.users.location),
        role = case
          when new.raw_user_meta_data ->> 'role' in ('client', 'fundi', 'admin') then new.raw_user_meta_data ->> 'role'
          else public.users.role
        end,
        "updatedAt" = now();
  return new;
end;
$$;

drop trigger if exists mjengolink_auth_user_sync on auth.users;
create trigger mjengolink_auth_user_sync
  after insert or update of email, raw_user_meta_data on auth.users
  for each row execute function public.sync_mjengolink_auth_user();

insert into public.users (auth_user_id, email, name, location, role)
select
  id,
  email,
  nullif(trim(raw_user_meta_data ->> 'name'), ''),
  nullif(trim(raw_user_meta_data ->> 'location'), ''),
  case
    when raw_user_meta_data ->> 'role' in ('client', 'fundi', 'admin') then raw_user_meta_data ->> 'role'
    else 'user'
  end
from auth.users
on conflict (auth_user_id) do update
  set email = excluded.email,
      name = coalesce(excluded.name, public.users.name),
      location = coalesce(excluded.location, public.users.location),
      "updatedAt" = now();

create or replace function public.set_mjengolink_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  new."updatedAt" = now();
  return new;
end;
$$;

drop trigger if exists users_set_updated_at on public.users;
create trigger users_set_updated_at before update on public.users
  for each row execute function public.set_mjengolink_updated_at();
drop trigger if exists worker_profiles_set_updated_at on public.worker_profiles;
create trigger worker_profiles_set_updated_at before update on public.worker_profiles
  for each row execute function public.set_mjengolink_updated_at();
drop trigger if exists jobs_set_updated_at on public.jobs;
create trigger jobs_set_updated_at before update on public.jobs
  for each row execute function public.set_mjengolink_updated_at();
drop trigger if exists conversations_set_updated_at on public.conversations;
create trigger conversations_set_updated_at before update on public.conversations
  for each row execute function public.set_mjengolink_updated_at();

