-- Run once in the Supabase SQL Editor for an existing MjengoLink database.
-- Adds real in-app notifications for interest, decisions, chats and messages.

create table if not exists public.notifications (
  id integer generated by default as identity primary key,
  "userId" integer not null references public.users (id) on delete cascade,
  type varchar(32) not null,
  title varchar(160) not null,
  body varchar(500) not null,
  "jobId" varchar(32) references public.jobs (id) on delete cascade,
  "conversationId" integer references public.conversations (id) on delete cascade,
  "readAt" timestamptz,
  "createdAt" timestamptz not null default now()
);

create index if not exists notifications_user_created_idx
  on public.notifications ("userId", "createdAt" desc);

alter table public.notifications enable row level security;
revoke all on table public.notifications from anon, authenticated;
