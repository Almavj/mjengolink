-- Run once in the Supabase SQL Editor for an existing MjengoLink database.
-- Keeps production tables aligned with drizzle/schema.ts.

alter table public.users add column if not exists location varchar(255);
alter table public.users add column if not exists avatar_path text;

-- Service areas must come from each user, never from a hard-coded demo location.
alter table public.worker_profiles alter column "serviceArea" drop default;

create or replace function public.set_mjengolink_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  new."updatedAt" = now();
  return new;
end;
$$;

create table if not exists public.conversations (
  id integer generated by default as identity primary key,
  "jobId" varchar(32) not null references public.jobs (id) on delete cascade,
  "clientId" integer not null references public.users (id),
  "workerId" integer not null references public.worker_profiles (id) on delete cascade,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  constraint conversations_job_worker_unique unique ("jobId", "workerId")
);

create table if not exists public.messages (
  id integer generated by default as identity primary key,
  "conversationId" integer not null references public.conversations (id) on delete cascade,
  "senderId" integer not null references public.users (id),
  body varchar(2000) not null,
  "createdAt" timestamptz not null default now(),
  "readAt" timestamptz
);

create index if not exists conversations_client_updated_idx
  on public.conversations ("clientId", "updatedAt" desc);
create index if not exists conversations_worker_updated_idx
  on public.conversations ("workerId", "updatedAt" desc);
create index if not exists messages_conversation_created_idx
  on public.messages ("conversationId", "createdAt");

drop trigger if exists conversations_set_updated_at on public.conversations;
create trigger conversations_set_updated_at before update on public.conversations
  for each row execute function public.set_mjengolink_updated_at();

alter table public.conversations enable row level security;
alter table public.messages enable row level security;
revoke all on table public.conversations, public.messages from anon, authenticated;

-- Keep registration metadata (name, location, role) in the public profile table.
create or replace function public.sync_mjengolink_auth_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  insert into public.users (auth_user_id, email, name, location, role)
  values (
    new.id,
    new.email,
    nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
    nullif(trim(new.raw_user_meta_data ->> 'location'), ''),
    case
      when new.raw_user_meta_data ->> 'role' in ('client', 'fundi', 'admin') then new.raw_user_meta_data ->> 'role'
      else 'user'
    end
  )
  on conflict (auth_user_id) do update
    set email = excluded.email,
        name = coalesce(excluded.name, public.users.name),
        location = coalesce(nullif(trim(new.raw_user_meta_data ->> 'location'), ''), public.users.location),
        role = case
          when new.raw_user_meta_data ->> 'role' in ('client', 'fundi', 'admin') then new.raw_user_meta_data ->> 'role'
          else public.users.role
        end,
        "updatedAt" = now();
  return new;
end;
$$;

drop trigger if exists mjengolink_auth_user_sync on auth.users;
create trigger mjengolink_auth_user_sync
  after insert or update of email, raw_user_meta_data on auth.users
  for each row execute function public.sync_mjengolink_auth_user();

-- Private bucket for user-selected profile photos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('profile-photos', 'profile-photos', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Users can read their own profile photos" on storage.objects;
create policy "Users can read their own profile photos"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'profile-photos'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
drop policy if exists "Users can upload their own profile photos" on storage.objects;
create policy "Users can upload their own profile photos"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'profile-photos'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
drop policy if exists "Users can update their own profile photos" on storage.objects;
create policy "Users can update their own profile photos"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'profile-photos'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  )
  with check (
    bucket_id = 'profile-photos'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
drop policy if exists "Users can delete their own profile photos" on storage.objects;
create policy "Users can delete their own profile photos"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'profile-photos'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
